<!--
  Переключатель из нескольких значений. Варианты приходят парами
  «значение — подпись»: подпись переводится, значение уходит демону как есть.
-->
<script>
  let { options = [], value, onselect } = $props();
</script>

<div class="segmented">
  {#each options as option (option.value)}
    <button
      class="seg"
      class:active={option.value === value}
      onclick={() => onselect?.(option.value)}
    >
      {option.label}
    </button>
  {/each}
</div>

<style>
  /*
   * Рамка постоянная, и её наличие решает тема — тот же `--sunken-edge`, что
   * и у панели вкладок.
   *
   * На тёмном она нужна: подложка группы отличается от тела окна на пятнадцать
   * единиц яркости, и без рамки край группы угадывается. На светлом серая
   * группа на белом видна сама, и рамка становится второй линией у того же
   * края — в окне из полутора десятков настроек такие удвоения складываются
   * в решётку, где нечему выделиться.
   */
  .segmented {
    display: flex;
    gap: 2px;
    padding: 2px;
    border-radius: 5px;
    background: var(--bg-sunken);
    box-shadow: inset 0 0 0 0.5px var(--sunken-edge);
  }

  /*
   * На наведение группа не отвечает вовсе — как и панель вкладок.
   *
   * Отвечать ей было нечем. Кольцо вокруг одного сегмента рисуется внутри
   * общей рамки — получаются рамка в рамке и разрезанная надвое группа;
   * подсветка всей группы отвечает не на «сюда можно нажать», а на «курсор
   * где-то здесь», и при этом разгорается и гаснет вслед за каждым движением
   * мыши вдоль ряда. Выбранный сегмент и так закрашен, остальные и так
   * нажимаются — вопроса, на который отвечала бы обводка, тут нет.
   */
  .seg:hover {
    outline: none;
  }

  .seg {
    padding: 2.5px 6px;
    border: 0;
    border-radius: 3px;
    background: transparent;
    color: rgba(var(--fg-rgb), 0.62);
    font-family: inherit;
    font-size: 9px;
    font-weight: 500;
    line-height: 100%;
    white-space: nowrap;
    cursor: pointer;
  }

  /*
   * Выбранный сегмент — плашка поверх серой подложки, а не акцентная заливка.
   *
   * В тёмной теме разницы нет. В светлой чернильный сегмент внутри серой
   * группы читается как отдельная кнопка, а не как «вот это выбрано»: тёмное
   * пятно тяжелее всей группы, в которой стоит. Белая плашка на сером говорит
   * то же самое и не перетягивает вес на себя.
   */
  .active {
    background: var(--raised);
    color: var(--on-raised);
    /* Светлое на тёмном кажется жирнее — ступень вниз выравнивает. */
    font-weight: calc(500 + var(--on-raised-weight));
  }
</style>
