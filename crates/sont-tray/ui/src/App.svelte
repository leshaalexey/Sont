<!--
  Окно целиком: 300×350. Всё, что внутри, разложено по компонентам в
  `lib/` — правка одного элемента не требует поиска по общему файлу.
-->
<script>
  import TitleBar from "./lib/TitleBar.svelte";
  import Tabs from "./lib/Tabs.svelte";
  import Toast from "./lib/Toast.svelte";
  import Conductor from "./lib/tabs/Conductor.svelte";
  import Keys from "./lib/tabs/Keys.svelte";
  import System from "./lib/tabs/System.svelte";
  import { settings, start } from "./lib/daemon.js";

  let tab = $state("conductor");
  let scroll = $state(null);

  // Полоса прокрутки показывается на время движения и гаснет сама.
  let scrolling = $state(false);
  let idle;

  function moved() {
    scrolling = true;
    clearTimeout(idle);
    idle = setTimeout(() => (scrolling = false), 700);
  }

  // Куда должен доехать список и кадр, который его туда ведёт.
  let target = null;
  let gliding = 0;

  /**
   * Прокрутка колесом — своя, а не браузерная.
   *
   * WebView2 доводит колесо инерцией: список продолжает ехать после того, как
   * его перестали крутить. На странице это приятно, а в окне высотой в три
   * сотни точек — промах мимо нужной строки: докрутить до конца и
   * остановиться там невозможно.
   */
  function wheel(event) {
    event.preventDefault();
    // `deltaMode` бывает в строках и в страницах — колесо мыши отдаёт
    // строки, тачпад пиксели. Приводим к точкам, иначе шаг мыши выйдет в
    // единицы пикселей.
    const step = event.deltaMode === 1 ? 16 : event.deltaMode === 2 ? scroll.clientHeight : 1;
    const limit = scroll.scrollHeight - scroll.clientHeight;

    // Цель накапливается: второй щелчок колеса, пришедший посреди движения,
    // добавляется к оставшемуся пути, а не отменяет его.
    target = Math.max(0, Math.min(limit, (target ?? scroll.scrollTop) + event.deltaY * step));
    if (!gliding) gliding = requestAnimationFrame(glide);
    moved();
  }

  /**
   * Догоняет цель за несколько кадров.
   *
   * Колесо мыши отдаёт крупные ступени — сотня точек за щелчок, — и прыжок
   * ровно на неё читается рывком: глазу не за что зацепиться, чтобы понять,
   * куда уехал список. Тачпад шлёт мелкие пиксельные приращения, и там этого
   * не видно; отсюда и «на тачпаде нормально».
   *
   * Это не инерция: путь ограничен тем, что накрутили, и заканчивается точно
   * на цели. Инерция — когда список едет дальше уже после того, как его
   * перестали крутить.
   */
  function glide() {
    const was = scroll.scrollTop;
    const gap = target - was;

    if (Math.abs(gap) < 0.5) {
      scroll.scrollTop = target;
      target = null;
      gliding = 0;
      return;
    }

    scroll.scrollTop += gap * 0.22;

    // Шаг мог не дойти до целого пикселя устройства и пропасть в округлении —
    // масштаб окна полуторный, и позиция прокрутки ложится не на любое
    // значение. Без этой проверки кадры продолжали бы заказываться вечно,
    // догоняя цель, до которой не добраться.
    if (scroll.scrollTop === was) {
      target = null;
      gliding = 0;
      return;
    }
    gliding = requestAnimationFrame(glide);
  }

  // Панель выезжает снизу и уезжает туда же — как прочие всплывающие окна
  // Windows 11. Двигается содержимое, а не само окно: перемещать окно по
  // таймеру означало бы дёрганое движение, а тут анимацию ведёт композитор.
  let shown = $state(false);

  const appWindow = window.__TAURI__?.window?.getCurrentWindow?.();
  const listen = window.__TAURI__?.event?.listen;

  // Длительность выезда берётся из той же переменной, что и анимация: два
  // независимых числа рано или поздно разъезжаются, и окно начинает
  // пропадать, не доехав до края.
  const SLIDE_MS =
    parseFloat(getComputedStyle(document.documentElement).getPropertyValue("--slide")) || 320;

  start();

  $effect(() => {
    // Кадр задержки нужен, чтобы браузер увидел начальное положение и было
    // что анимировать: без него панель просто появляется на месте.
    requestAnimationFrame(() => (shown = true));
  });

  // Отложенное скрытие окна. Держим ссылку, чтобы отменить: без этого
  // быстрое «закрыл — открыл» пряталось на полпути — открытое окно исчезало
  // от таймера, поставленного предыдущим закрытием.
  let hiding;

  if (listen) {
    listen("sont://hide", async () => {
      shown = false;
      // Ждём конец анимации, потом убираем окно. Иначе следующий показ
      // начнётся с уже уехавшей панели.
      //
      // Срок с запасом: настоящим сигналом служит `transitionend` на самой
      // панели, а таймер нужен на случай, когда перехода не было вовсе —
      // окно уже внизу, движок не рисует, пользователь выключил анимации в
      // системе. Без запаса таймер срабатывал бы посреди движения.
      clearTimeout(hiding);
      hiding = setTimeout(() => appWindow?.hide(), SLIDE_MS + 120);
    });
    listen("sont://show", () => {
      clearTimeout(hiding);
      shown = true;
    });
  }

  /** Панель доехала вниз — теперь окно можно убирать. */
  function settled(event) {
    if (shown || event.propertyName !== "transform") return;
    clearTimeout(hiding);
    appWindow?.hide();
  }

  /**
   * Гасит браузерное меню по правой кнопке.
   *
   * «Обновить», «Просмотреть код», «Сохранить как» — пункты страницы, а не
   * приложения: половина из них здесь бессмысленна, вторая половина ломает
   * окно. В поле ввода меню остаётся: там оно своё, с «вставить», и без него
   * ключ подписки пришлось бы набирать руками.
   */
  function menu(event) {
    if (event.target.closest("input")) return;
    event.preventDefault();
  }

  function select(next) {
    tab = next;
    // Каждая вкладка начинается сверху: унаследованная прокрутка от соседней
    // выглядит как потерянный кусок страницы.
    if (scroll) scroll.scrollTop = 0;
  }
</script>

<div class="window" class:shown ontransitionend={settled} oncontextmenu={menu}>
  <TitleBar />

  <main class="body">
    <Tabs active={tab} onselect={select} />

    <div
      class="scroll"
      class:scrolling
      bind:this={scroll}
      onscroll={moved}
      onwheel={wheel}
    >
      {#if $settings}
        <div class="page">
          {#if tab === "conductor"}
            <Conductor />
          {:else if tab === "keys"}
            <Keys />
          {:else}
            <System />
          {/if}
        </div>
      {/if}
    </div>
  </main>

  <Toast />
</div>

<style>
  .window {
    position: relative;
    width: var(--win-w);
    height: var(--win-h);
    overflow: hidden;
    /*
     * Скругление — как у системных всплывающих панелей: угол восемь точек.
     *
     * Делится на масштаб, потому что `zoom` умножает все размеры: восемь
     * точек макета при полуторном увеличении превратились бы в двенадцать
     * экранных, и угол рядом с системными панелями смотрелся бы круглее.
     * Здесь нужны именно экранные восемь.
     */
    border-radius: calc(8px / var(--ui-scale));
    background: var(--bg);

    /*
     * Скругление режется `clip-path`, а не одним `overflow: hidden`.
     *
     * Окно — композитный слой: у него есть `transform` для выезда снизу.
     * Скруглённый `overflow` на таком слое Chromium применяет к готовой
     * текстуре и без сглаживания, отчего по углам оставались светлые
     * ступеньки — угол выглядел обкусанным. `clip-path` режет с тем же
     * сглаживанием, что и обычная отрисовка.
     */
    clip-path: inset(0 round calc(8px / var(--ui-scale)));

    /*
     * Выезд снизу — одним движением, без проявления.
     *
     * Прозрачность из анимации убрана: панель, которая одновременно едет и
     * проступает, читается размыто, а край окна во время движения выглядит
     * рваным. Едет непрозрачная панель — движение видно чисто.
     *
     * Кривая — затухающая экспонента: трогается быстро, у края долго
     * успокаивается. Прежние сто восемьдесят миллисекунд с равномерным
     * замедлением давали не выезд, а рывок.
     */
    /*
     * Прячется панель не ровно на свою высоту, а с запасом.
     *
     * Ровно ста процентов хватало бы при равномерном движении, но кривая
     * здесь затухающая: основную часть пути панель проходит сразу, а
     * последние точки доползает долго. Нижняя полоска оставалась на экране
     * до самого конца перехода, и окно пряталось прямо на ней — уход
     * обрывался, не досмотренный до конца.
     *
     * С запасом видимая часть уходит за край задолго до конца перехода, а
     * доползают уже те точки, которых не видно.
     */
    transform: translateY(125%);
    transition: transform var(--slide) cubic-bezier(0.22, 1, 0.36, 1);
    will-change: transform;
  }

  /*
   * Обводка — отдельным слоем поверх содержимого.
   *
   * Раньше это была `inset`-тень на самом окне, и её не было видно: шапка и
   * тело — обычные потомки со своим фоном, и они закрашивали её по всем
   * четырём сторонам. Окно оставалось без края и сливалось с собственной
   * тенью.
   *
   * Линия одна и лежит на самой кромке.
   *
   * Их было две — тёмная на первой точке, светлая на второй. На тёмном фоне
   * панели тёмная сливалась с ней, и глазу оставалась только светлая, то
   * есть линия, отступившая от края на точку: обводка выглядела не рамкой
   * окна, а рамкой чего-то внутри него. Одна линия по кромке такого повода
   * не даёт.
   *
   * Изнутри, а не снаружи: снаружи её обрезало бы скругление окна.
   */
  .window::after {
    content: "";
    position: absolute;
    inset: 0;
    border-radius: inherit;
    /*
     * Цвет непрозрачный. Полупрозрачная линия смешивалась с тем, что под
     * ней, а под ней в верхней полосе шапка (18, 18, 17), а ниже — тело
     * (33, 33, 33): одна и та же обводка выходила двух разных оттенков.
     * Теперь она одинакова по всему периметру.
     */
    box-shadow: inset 0 0 0 calc(1px / var(--ui-scale)) rgb(68, 66, 64);
    pointer-events: none;
  }

  .shown {
    transform: translateY(0);
  }

  /* Без собственной тени: размытая тёмная кайма по периметру тела читалась
     второй, внутренней рамкой рядом с настоящей обводкой окна. */
  .body {
    position: absolute;
    inset: 26px 0 0 0;
    background: var(--bg);
  }

  /*
   * Область прокрутки занимает всю ширину окна, а поля держит содержимое.
   * Так полоса прокрутки оказывается у настоящего края, а не посреди
   * пустого отступа.
   *
   * Без скругления. Оно обрезало углы содержимого, и первая строка настроек
   * въезжала в срез — скругление у окна уже есть, а внутренняя коробка
   * ничем не выделена, чтобы его повторять.
   */
  .scroll {
    position: absolute;
    inset: 36px 0 6px 0;
    overflow: hidden auto;
    /* Прокрутка не уходит на окно целиком, когда список кончился. */
    overscroll-behavior: contain;
    /*
     * Жёлоб под полосу резервируется с обеих сторон и всегда.
     *
     * Иначе появление полосы отнимает ширину только справа, и содержимое
     * дёргается влево при переходе на длинную вкладку — а на короткой стоит
     * не по центру окна, а со сдвигом. Симметричный жёлоб держит колонку
     * посередине независимо от того, есть прокрутка или нет.
     */
    scrollbar-gutter: stable both-edges;
  }

  /*
   * Полоса прокрутки стоит у самого края окна, а поля держит содержимое:
   * `.page` отступает от краёв само. Раньше отступ был у контейнера, и полоса
   * висела посреди пустого поля, будто ещё один элемент интерфейса.
   *
   * Видимая часть ползунка — три точки; остальное в жёлобе занимают
   * прозрачные поля, отодвигающие его от текста слева и оставляющие две
   * точки до обводки окна справа.
   */
  .scroll::-webkit-scrollbar {
    width: 8px;
  }
  .scroll::-webkit-scrollbar-thumb {
    background: transparent;
    border-left: 3px solid transparent;
    border-right: 2px solid transparent;
    background-clip: padding-box;
    border-radius: 4px;
    transition: background 220ms var(--ease);
  }
  .scroll::-webkit-scrollbar-track {
    background: transparent;
  }

  /*
   * Ползунок виден, только пока идёт прокрутка. В окне на триста точек
   * постоянная полоса — это отнятая ширина и лишняя линия рядом с
   * настройками; о том, что список длиннее окна, она сообщает ровно в тот
   * момент, когда это уже и так видно по движению.
   */
  .scrolling::-webkit-scrollbar-thumb {
    background: rgba(244, 237, 229, 0.18);
    background-clip: padding-box;
  }

  .page {
    display: flex;
    flex-direction: column;
    padding: 2px 11px 12px 11px;
  }
</style>
