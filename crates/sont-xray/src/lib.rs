//! Ядро туннеля на базе Xray-core.
//!
//! # Почему Xray
//!
//! Выбор сделан не из общих соображений, а по фактам: панели, которыми
//! пользуются в этом сегменте, выдают VLESS с транспортом XHTTP, а его
//! реализует только Xray — upstream sing-box такого транспорта не имеет.
//! Дополнительно Xray распространяется под MPL-2.0, что снимает обязательства
//! GPL-3.0, и располагает встроенным TUN-inbound и маршрутизацией по процессам
//! (Windows и Linux), на которой держится раздельное туннелирование.
//!
//! Цена решения: Xray не умеет TUIC, а правила по процессам не работают на
//! macOS. Оба ограничения проверяются явно — см. [`supports`].
//!
//! # Граница безопасности
//!
//! Конфигурация собирается здесь и только здесь, из типизированных
//! [`sont_core::Transport`]. Готовый JSON никогда не приходит извне: у ядра
//! есть outbound-ы, способные обращаться к произвольным адресам, а запускается
//! оно от SYSTEM/root.

pub mod config;
pub mod metrics;
pub mod support;

pub use config::{build, build_race, BuildError, RuntimeInfo};
